package fr.epistudio.epysia.lang.rust;

import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.HashSet;
import java.util.List;
import java.util.Set;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import java.util.stream.Collectors;
import java.util.stream.Stream;

final class RustCrateSync {

    static final String CRATE_NAME = "epysia-scripts";

    private static final String[] SDK_RESOURCE_FILES = {
            "epysia-sdk/Cargo.toml",
            "epysia-sdk/src/lib.rs",
            "epysia-sdk/src/abi.rs",
            "epysia-sdk/src/transform.rs",
            "epysia-sdk/src/input.rs",
            "epysia-sdk/src/vec3.rs",
            "epysia-macros/Cargo.toml",
            "epysia-macros/src/lib.rs",
    };

    private static final Pattern COMPONENT_PATTERN = Pattern.compile(
            "#\\[\\s*epysia_component[^\\]]*\\]"
                    + "(?:\\s*#\\[[^\\]]*\\])*"
                    +"\\s*(?:pub\\s+)?struct\\s+(\\w+)");

    private RustCrateSync() {
    }

    static Path buildDirectoryFor(Path scriptsDirectory) {
        return scriptsDirectory.resolveSibling(".epysia-rust-build");
    }

    static Path wasmArtifact(Path crateDirectory) {
        String fileName = CRATE_NAME.replace('-', '_') + ".wasm";
        return crateDirectory.resolve("target").resolve("wasm32-unknown-unknown").resolve("release").resolve(fileName);
    }

    static Path sync(Path scriptsDirectory, List<Path> sources) throws IOException {
        Path buildDirectory = buildDirectoryFor(scriptsDirectory);
        Path sdkDirectory = buildDirectory.resolve("sdk");
        Path crateDirectory = buildDirectory.resolve("crate");
        Path srcDirectory = crateDirectory.resolve("src");

        materializeSdk(sdkDirectory);
        List<ModuleEntry> modules = syncSources(srcDirectory, sources);
        removeStaleModules(srcDirectory, modules.stream().map(module -> module.fileName).collect(Collectors.toSet()));

        List<String> componentPaths = new ArrayList<>();
        for (ModuleEntry module : modules) {
            for (String struct : module.structs) {
                componentPaths.add(module.name + "::" + struct);
            }
        }

        writeIfChanged(crateDirectory.resolve("Cargo.toml"), cargoTomlFor());
        writeIfChanged(srcDirectory.resolve("lib.rs"), libRsFor(modules, componentPaths));
        return crateDirectory;
    }

    private static void materializeSdk(Path sdkDirectory) throws IOException {
        for (String relative : SDK_RESOURCE_FILES) {
            String content;
            try (InputStream stream = RustCrateSync.class.getResourceAsStream("/" + relative)) {
                if (stream == null) {
                    throw new IllegalStateException("Rust SDK resource missing from the pack: " + relative);
                }
                content = new String(stream.readAllBytes(), StandardCharsets.UTF_8);
            }
            writeIfChanged(sdkDirectory.resolve(relative), content);
        }
    }

    private static List<ModuleEntry> syncSources(Path srcDirectory, List<Path> sources) throws IOException {
        List<ModuleEntry> modules = new ArrayList<>();
        Set<String> usedNames = new HashSet<>();
        int anonymousIndex = 0;
        for (Path source : sources) {
            String moduleName = uniqueModuleName(baseNameOf(source), usedNames, anonymousIndex++);
            usedNames.add(moduleName);
            String content = Files.readString(source, StandardCharsets.UTF_8);
            writeIfChanged(srcDirectory.resolve(moduleName + ".rs"), content);
            modules.add(new ModuleEntry(moduleName, moduleName + ".rs", structNamesIn(content)));
        }
        return modules;
    }

    private static void removeStaleModules(Path srcDirectory, Set<String> currentFiles) throws IOException {
        if (!Files.isDirectory(srcDirectory)) {
            return;
        }
        try (Stream<Path> children = Files.list(srcDirectory)) {
            for (Path child : children.toList()) {
                String fileName = child.getFileName().toString();
                if (fileName.equals("lib.rs") || !fileName.endsWith(".rs") || currentFiles.contains(fileName)) {
                    continue;
                }
                Files.deleteIfExists(child);
            }
        }
    }

    private static String cargoTomlFor() {
        return """
                # generated by Epysia's Rust language pack, do not edit by hand
                [package]
                name = "%s"
                version = "0.1.0"
                edition = "2021"

                [lib]
                crate-type = ["cdylib"]

                [dependencies]
                epysia-sdk = { path = "../sdk/epysia-sdk" }

                [profile.release]
                lto = true
                opt-level = "s"
                strip = true
                """.formatted(CRATE_NAME);
    }

    private static String libRsFor(List<ModuleEntry> modules, List<String> componentPaths) {
        StringBuilder source = new StringBuilder("// generated by Epysia's Rust language pack, do not edit by hand\n\n");
        for (ModuleEntry module : modules) {
            source.append("mod ").append(module.name).append(";\n");
        }
        source.append("\nepysia_sdk::epysia_crate! {\n");
        for (String path : componentPaths) {
            source.append("    ").append(path).append(",\n");
        }
        source.append("}\n");
        return source.toString();
    }

    private static String baseNameOf(Path source) {
        String fileName = source.getFileName().toString();
        int dot = fileName.lastIndexOf('.');
        return dot > 0 ? fileName.substring(0, dot) : fileName;
    }

    private static String uniqueModuleName(String stem, Set<String> used, int anonymousIndex) {
        String base = snakeCase(stem);
        if (base.isEmpty()) {
            base = "script_" + anonymousIndex;
        }
        String candidate = base;
        int suffix = 1;
        while (used.contains(candidate)) {
            candidate = base + "_" + (++suffix);
        }
        return candidate;
    }

    private static String snakeCase(String name) {
        StringBuilder result = new StringBuilder(name.length() + 4);
        for (int index = 0; index < name.length(); index++) {
            char character = name.charAt(index);
            if (Character.isUpperCase(character)) {
                if (index > 0) {
                    result.append('_');
                }
                result.append(Character.toLowerCase(character));
            } else if (Character.isLetterOrDigit(character) || character == '_') {
                result.append(character);
            } else {
                result.append('_');
            }
        }
        if (!result.isEmpty() && Character.isDigit(result.charAt(0))) {
            result.insert(0, '_');
        }
        return result.toString();
    }

    private static List<String> structNamesIn(String content) {
        List<String> names = new ArrayList<>();
        Matcher matcher = COMPONENT_PATTERN.matcher(content);
        while (matcher.find()) {
            names.add(matcher.group(1));
        }
        return names;
    }

    private static void writeIfChanged(Path file, String content) throws IOException {
        if (Files.isRegularFile(file) && Files.readString(file, StandardCharsets.UTF_8).equals(content)) {
            return;
        }
        Files.createDirectories(file.getParent());
        Files.writeString(file, content, StandardCharsets.UTF_8);
    }

    private record ModuleEntry(String name, String fileName, List<String> structs) {
    }
}
